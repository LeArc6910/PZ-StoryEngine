--   next/win/lose 에 { default, list = { { 플래그, id }, ... } (앞에서부터), when = { { npc, node | arc, go } } }
--               when: 다른 NPC 가 지금 그 노드(또는 그 이야기)에 있으면 go 로 (이야기끼리 얽힘)
--   fate        { kind = "dead" | "gone", text } 그 결말에 들어서면 하루 뒤 정말 죽거나 떠난다 (Fate.onStoryFate)
